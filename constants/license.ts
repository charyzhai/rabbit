// 激活授权相关的混淆常量（请勿手动修改）。
//
// 设计目标：抵御「直接反编译搜索明文激活码」的破解。
// - 激活码本身（明文 "wency"）绝不出现在安装包内；
// - 仅保存其 SHA-256 哈希值，且哈希被拆成两段，分别存放在本文件与
//   lib/activation.ts 中，运行时再拼接，避免单一完整 64 位十六进制串可被直接搜索；
// - 校验时对用户输入做同样的哈希并用常量时间比较，杜绝计时侧信道；
// - 激活成功后在加密存储中写入的是「派生令牌（即该哈希）」而非布尔值，
//   因此仅把存储改写成 "true" 无法绕过校验。
//
// 真要在纯 JS 包里做到绝对不可破解是不可能的（逆向者可改判定逻辑），
// 这里把破解成本从「搜索字符串」提升到「定位/重组哈希并改字节码」。

// 激活码哈希的前 32 位（与 lib/activation.ts 中的后 32 位拼接）
